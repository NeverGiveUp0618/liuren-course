class Reader(HTMLParser):
    def __init__(self):
        super().__init__()
        self.in_h2 = False
        self.p_kind = None
        self.buf = []
        self.current = None
        self.items = []

    def handle_starttag(self, tag, attrs):
        attrs = dict(attrs)
        if tag == "h2":
            self.in_h2, self.buf = True, []
        elif tag == "p" and attrs.get("class") in ("o", "t"):
            self.p_kind, self.buf = attrs["class"], []

    def handle_data(self, data):
        if self.in_h2 or self.p_kind:
            self.buf.append(data)

    def handle_endtag(self, tag):
        if tag == "h2" and self.in_h2:
            self.current = {"h": clean("".join(self.buf)), "p": []}
            self.items.append(self.current)
            self.in_h2 = False
        elif tag == "p" and self.p_kind:
            if self.current is not None:
                self.current["p"].append((self.p_kind, clean("".join(self.buf))))
            self.p_kind = None


def clean(s):
    return " ".join(s.split())


