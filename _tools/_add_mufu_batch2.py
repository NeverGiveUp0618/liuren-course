def load_source():
    cache = Path("/tmp/renzhan.html")
    if cache.exists() and cache.stat().st_size > 1_000_000:
        return cache.read_text(encoding="utf-8")
    req = urllib.request.Request(SOURCE_URL, headers={"User-Agent": "Mozilla/5.0"})
    with urllib.request.urlopen(req, timeout=30) as r:
        return r.read().decode("utf-8")


def originals(item):
    paras = [text for kind, text in item["p"] if kind == "o"]
    start = next(j for j, text in enumerate(paras)
                 if re.search(r"王牧夫(?:曰|断曰)", text))
    out = paras[start:]
    # 公版底本缺字统一用方框，不把现代猜字塞回古文。
    return [re.sub(r"[？?]+", lambda m: "□" * len(m.group()), p) for p in out]


def render(case, item, n):
    board = build({"r": case["r"], "yj": case["yj"], "zs": case["zs"], "sc": list(case["sc"])})
    lines = [
        f"### 【入门例{n}】{case['r']}日 · {case['title']} " + " ".join(f"`{x}`" for x in case["tags"].split()),
        "",
        f"**格**：{case['ke']} · {case['yj']}将加{case['zs']}时 · 三传{'→'.join(case['sc'])}",
        "",
        f"**占问**：{case['q']}",
        "",
        md_pan(board), "", "**四课**", "", md_sike(board), "", "**三传**", "", md_sanchuan(board),
        "", "**古文原断**", "",
    ]
    for para in originals(item):
        lines.extend([f"> {para}", ">"])
    if lines[-1] == ">":
        lines.pop()
    lines.extend(["", "**白话拆解**", ""])
    nums = "①②③④"
    for j, (head, body) in enumerate(case["steps"]):
        lines.extend([f"**第{nums[j]}步　{head}**", "", f"- {body}", ""])
    lines.extend([
        f"**断语**：{case['steps'][-1][1]}", "",
        f"**初学记忆**：{case['memo']}", "",
        "〔出处〕程树勋《壬占汇选》所录《牧夫占验》；古文据公开电子整理本核录，盘面按本站第 2—7 课规则复排。",
        "", "---", "",
    ])
    return "\n".join(lines)


def main():
    text = TARGET.read_text(encoding="utf-8")
    if "【入门例55】" in text:
        print("王牧夫入门例 26—55 已存在，跳过。")
        return
    if len(re.findall(r"^### 【入门例", text, flags=re.M)) != 25:
        raise SystemExit("案例数不是 25，拒绝追加，避免重号或覆盖。")

    parser = Reader()
    parser.feed(load_source())
    source_cases = [x for x in parser.items if "牧夫占验" in x["h"]]
    if len(source_cases) < 57:
        raise SystemExit(f"来源只解析到 {len(source_cases)} 例，拒绝生成。")

    blocks = ["## 第三批三十例（入门例26—55）", ""]
    for n, case in enumerate(CASES, 26):
        blocks.append(render(case, source_cases[case["i"] - 1], n))
    text = text.replace("第二批再增 20 例，现共 25 例。", "第二批增 20 例，第三批再增 30 例，现共 55 例。")
    TARGET.write_text(text.rstrip() + "\n\n" + "\n".join(blocks).rstrip() + "\n", encoding="utf-8")
    print("已追加王牧夫入门例 26—55。")


