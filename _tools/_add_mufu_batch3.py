def all_source_cases():
    parser = Reader()
    parser.feed(load_source())
    return [x for x in parser.items
            if "牧夫占验" in x["h"] or any("牧夫占验" in v or "王牧夫" in v for _, v in x["p"])]


def render_residual(case, item, n):
    paras = [re.sub(r"[？?]+", lambda m: "□" * len(m.group()), v)
             for k, v in item["p"] if k == "o"]
    out = [f"### 【入门例{n}】残案 · {case['title']} " + " ".join(f"`{x}`" for x in case["tags"].split()), "",
           "**格**：原书课盘遗失，不能复排", "", f"**占问**：{case['q']}", "",
           "> ⚠️ **盘面说明**：本例不展示天地盘、四课、三传。缺少起课日时或原课盘时，任何补盘都是伪造。", "",
           "**古文原断**", ""]
    for p in paras:
        out.extend(["> " + p, ">"])
    if out[-1] == ">": out.pop()
    out.extend(["", "**白话拆解**", ""])
    for j, (h, b) in enumerate(case["steps"]):
        out.extend([f"**第{'①②③'[j]}步　{h}**", "", f"- {b}", ""])
    out.extend([f"**断语**：{case['steps'][-1][1]}", "", f"**初学记忆**：{case['memo']}", "",
                "〔出处〕程树勋《壬占汇选》所录《牧夫占验》残案；古文据公开电子整理本核录。", "", "---", ""])
    return "\n".join(out)


def main():
    text = TARGET.read_text(encoding="utf-8")
    if "【入门例80】" in text:
        print("王牧夫相关占验已经收完，跳过。")
        return
    if len(re.findall(r"^### 【入门例", text, flags=re.M)) != 55:
        raise SystemExit("案例数不是 55，拒绝追加。")
    source = all_source_cases()
    if len(source) < 81:
        raise SystemExit(f"来源只解析到 {len(source)} 条，拒绝生成。")

    # 旧例13曾把原书「卯将寅时」倒写成「寅将卯时」，整例按原盘重建。
    fixed = render(FIX13, source[FIX13["i"] - 1], 13)
    text, changed = re.subn(r"^### 【入门例13】[\s\S]*?^---\n", fixed, text, count=1, flags=re.M)
    if changed != 1:
        raise SystemExit("没有定位到旧例13，拒绝继续。")

    entries = [(c["i"], "full", c) for c in COMPLETE] + [(c["i"], "residual", c) for c in RESIDUAL]
    entries.sort(key=lambda x: x[0])
    blocks = ["## 收官批次（入门例56—80）", ""]
    for n, (i, kind, case) in enumerate(entries, 56):
        item = source[i - 1]
        blocks.append(render(case, item, n) if kind == "full" else render_residual(case, item, n))
    text = text.replace("第二批增 20 例，第三批再增 30 例，现共 55 例。",
                        "第二批增 20 例、第三批增 30 例，收官批次再录 25 条，现共 80 条（其中 2 条原书明确标为残案）。")
    TARGET.write_text(text.rstrip() + "\n\n" + "\n".join(blocks).rstrip() + "\n", encoding="utf-8")
    print("已追加例56—80，并订正例13。")


if __name__ == "__main__":
    main()
