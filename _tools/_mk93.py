def cn2n(s):
    s = s.replace('其', '')
    if s == '十':
        return 10
    m = re.match(r'^([一二三四五六七八九]?)(十?)([一二三四五六七八九]?)$', s)
    a, b, c = m.groups()
    n = 0
    if b:
        n = (CN.index(a) + 1 if a else 1) * 10
    elif a:
        n = CN.index(a) + 1
    if c:
        n += CN.index(c) + 1
    return n


