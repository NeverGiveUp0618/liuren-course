def cite(pages):
    pages = sorted(set(pages))
    if len(pages) == 1:
        return '〔通解下 p%d｜PDF p%d〕' % (pages[0] + OFF, pages[0])
    return '〔通解下 p%d-%d｜PDF p%d-%d〕' % (pages[0] + OFF, pages[-1] + OFF, pages[0], pages[-1])


def load_paras():
    t = open(SRC, encoding='utf-8').read()
    a = t.find('第一节 金锁玉匙')
    b = t.find('第二节 斗罡法')
    seg = t[a:b]
    NEW = re.compile(r'^(其[一二三四五六七八九十]+、|[一二三四五六七八九十]+、|[子丑寅卯辰巳午未申酉戌亥]加|'
                     r'玄胎课象|注意：|说明：|金锁玉匙诗诀|传六壬课者|象类诗诀|根据此课|①)')
    page, paras, cur = 335, [], None
    for ln in seg.split('\n'):
        s = ln.strip()
        m = re.match(r'^第 (\d+) 页$', s)
        if m:
            page = int(m.group(1))
            continue
        if s in ('大六壬通解', '叶飘然大六壬讲义', '第七章 大六壬外编', ''):
            continue
        if NEW.match(s) or cur is None:
            cur = {'pages': [page], 'text': s}
            paras.append(cur)
        else:
            cur['text'] += s
            cur['pages'].append(page)
    return paras


